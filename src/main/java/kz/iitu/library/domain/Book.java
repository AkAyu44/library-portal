package kz.iitu.library.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.JoinTable;
import jakarta.persistence.ManyToMany;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.BatchSize;

import java.time.Instant;
import java.time.LocalDate;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;

/**
 * Lab 5: the domain object of the catalogue (id, title, author, year).
 * Lab 6: genre, availability and the publication date (variant 7).
 * Lab 7: createdAt — set by the server, never sent by a client.
 * Lab 8: no longer a record but a JPA entity mapped to the table "book".
 * JPA needs a no-argument constructor, a non-final class and mutable fields
 * (the persistence context writes them after loading and tracks their changes),
 * so a record — final, with final fields and no no-arg constructor — cannot be an entity.
 * Book is the owning side of both associations: it holds author_id and declares book_tag.
 */
@Entity
@Table(name = "book")
public class Book {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)   // PostgreSQL: bigint generated by default as identity
    private Long id;

    @Column(nullable = false, length = 120)
    private String title;

    @Enumerated(EnumType.STRING)                          // 'PROGRAMMING', not 2 — safe when the enum is reordered
    @Column(nullable = false, length = 20)
    private Genre genre;

    private int year;

    private boolean archived;

    // Lab 6: kept from the form of the catalogue
    private boolean available = true;

    @Column(name = "published_on")
    private LocalDate publishedOn;

    @Column(name = "created_at", updatable = false)
    private Instant createdAt = Instant.now();

    @Version                                              // optimistic locking: where id = ? and version = ?
    private long version;

    // the owning side of book -> author: the foreign key author_id lives in "book"
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "author_id")
    private Author author;

    // the owning side of book <-> tag: it declares the join table book_tag(book_id, tag_id)
    @ManyToMany
    @JoinTable(name = "book_tag",
               joinColumns = @JoinColumn(name = "book_id"),
               inverseJoinColumns = @JoinColumn(name = "tag_id"))
    @BatchSize(size = 20)                                 // tags of a whole page in one select ... where book_id in (...)
    private Set<Tag> tags = new HashSet<>();

    protected Book() { }                                  // JPA needs this one; protected keeps it out of our code

    public Book(String title, Genre genre, int year) {
        this.title = title;
        this.genre = genre;
        this.year = year;
    }

    public void addTag(Tag tag) {
        tags.add(tag);
    }

    public void clearTags() {
        tags.clear();
    }

    public Long getId() { return id; }

    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }

    public Genre getGenre() { return genre; }
    public void setGenre(Genre genre) { this.genre = genre; }

    public int getYear() { return year; }
    public void setYear(int year) { this.year = year; }

    public boolean isArchived() { return archived; }
    public void setArchived(boolean archived) { this.archived = archived; }

    public boolean isAvailable() { return available; }
    public void setAvailable(boolean available) { this.available = available; }

    public LocalDate getPublishedOn() { return publishedOn; }
    public void setPublishedOn(LocalDate publishedOn) { this.publishedOn = publishedOn; }

    public Instant getCreatedAt() { return createdAt; }

    public long getVersion() { return version; }

    public Author getAuthor() { return author; }

    /** Called by Author.addBook — the one place that keeps both sides of the link in step. */
    void setAuthor(Author author) { this.author = author; }

    public Set<Tag> getTags() { return Collections.unmodifiableSet(tags); }

    /** The associations are left out: printing them would load them, or recurse through Author.books. */
    @Override
    public String toString() {
        return "Book{id=" + id + ", title='" + title + "', genre=" + genre + ", year=" + year + "}";
    }
}
